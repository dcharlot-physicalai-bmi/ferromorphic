//! Closing a loop with spikes: controllers, central pattern generators, and the plants to check
//! them against.
//!
//! Every other module in this crate **perceives**. This one **acts**, which is the Physical AI
//! case: a spiking network is only interesting on a robot if the spikes come back out as torque,
//! and the argument for putting them there is energetic. A conventional digital controller samples
//! at a fixed rate and computes a fixed amount of arithmetic per sample whether or not anything is
//! happening. A spiking controller emits spikes in proportion to the **error**, so a robot sitting
//! still at its setpoint costs nothing, and the bill scales with how wrong it is rather than with
//! how often you look. That is the claim; this module makes it a measurement.
//!
//! # The lesson: three gains, one spike train
//!
//! A PID controller is usually drawn as three parallel computations. In spikes it is not. There is
//! **one** population encoding the error, and the proportional, integral and derivative terms are
//! three different **synaptic time constants** reading the same spikes:
//!
//! | term | synapse | mapped gain |
//! |------|---------|-------------|
//! | P | a first-order trace with time constant `tau_p` (unit DC gain) | `Kp = a_p · g` |
//! | I | a non-leaky accumulator — a synapse with infinite time constant | `Ki = a_i · g` |
//! | D | the difference of a fast and a slow trace — a synaptic high-pass | `Kd = a_d · g · (tau_slow − tau_fast)` |
//!
//! `g` is the encoder gain in **spikes per second per unit of error**, `a_p` and `a_d` are in
//! plant-input units × seconds per spike, `a_i` in plant-input units per spike. That is the whole
//! mapping, and it is exact rather than fitted — see [`SpikingPid`] for the derivation of each row.
//!
//! The consequence is the energetic one: **the three terms cost the same as one**, because they
//! share the spikes. Adding integral action to a spiking controller adds a synapse, not a spike.
//!
//! # Why the encoder is a sigma-delta modulator and not a leaky neuron
//!
//! [`SigmaDeltaEncoder`] is a non-leaky integrate-and-fire unit that **resets by subtracting its
//! threshold** rather than by returning to zero. That one choice is what makes the whole module
//! analytically checkable: the spike count over `T` seconds at constant input `x` is exactly
//! `floor(g · x · T)`, with no remainder thrown away and no dependence on the time step. Reset to
//! zero — which is what [`crate::neuron::IntegrateAndFire`] does, correctly, because that is what
//! the neuron model says — discards the sub-threshold remainder at every spike and makes the
//! realised rate depend on `dt`. Yoon (*LIF and Simplified SRM Neurons Encode Signals Into Spikes
//! Via a Form of Asynchronous Pulse Sigma-Delta Modulation*, IEEE Transactions on Neural Networks
//! and Learning Systems 28(5):1192–1205, 2017) is the paper that identifies the equivalence; the
//! lossless variant here is the engineering form of it.
//!
//! This is a real difference between a model of a neuron and a component of a controller, and it is
//! stated rather than hidden: the encoder in this module is **not** a biological neuron, and it does
//! not implement [`crate::neuron::Neuron`] for that reason.
//!
//! # Central pattern generators: locomotion without a trajectory
//!
//! A legged robot does not need a planned joint trajectory to walk. Two mutually inhibiting neural
//! populations, each fatiguing while it is active, alternate on their own: Brown's *half-centre*
//! (Graham Brown, *The intrinsic factors in the act of progression in the mammal*, Proceedings of
//! the Royal Society B 84:308–319, 1911). [`Matsuoka`] is the rate-model form that the robotics
//! literature actually uses (Matsuoka, *Sustained oscillations generated by mutually inhibiting
//! neurons with adaptation*, Biological Cybernetics 52:367–376, 1985), and [`HalfCentre`] is the
//! spiking form built from this crate's own adapting neurons.
//!
//! The property that makes either of them a gait generator is **anti-phase**: the two sides are
//! exactly half a cycle apart, which is a walk. [`phase_difference`] measures it and the tests here
//! assert it near π rather than asserting that a plot looks right.
//!
//! # SI units, and where a paper's own constants are kept
//!
//! Time in seconds, angle in radians, torque in newton-metres, current in amperes, voltage in
//! volts. [`Matsuoka`]'s `beta` and `w` are **dimensionless by construction** in the 1985 paper and
//! are kept that way, with the conversion to a torque command happening at the boundary in
//! [`Matsuoka::drive`] — the same policy [`crate::neuron::Izhikevich`] follows, and for the same
//! reason: a reader must be able to compare the constants to the source line by line.
//!
//! # What this module does not claim
//!
//! [`ScalarKalman`] is a **scalar, time-invariant** filter. It is not a Kalman filter for a robot:
//! there is no state vector, no covariance matrix, no Joseph form. It is here because the
//! steady-state gain of the scalar problem has a closed form that a population-coded estimator can
//! be checked against, and because the honest simpler thing with its limits written down is worth
//! more than a vector filter nobody verified. [`PopulationEstimator`] says in its own doc which of
//! its assumptions the population code violates.
//!
//! This review did not locate a published spiking implementation of a full covariance-propagating
//! Kalman filter whose gain was checked against the algebraic Riccati solution; the nearest
//! published work is the probabilistic-population-code line (Deneve, Latham and Pouget, *Efficient
//! computation and cue integration with noisy population codes*, Nature Neuroscience 4:826–831,
//! 2001), which computes the same integration in a different representation.
//!
//! # Quickstart
//!
//! ```
//! use ferromorphic::control::{FirstOrder, SpikingPid, SpikingPidSpec};
//!
//! let spec = SpikingPidSpec::proportional(2_000.0, 4.0, 10e-3);
//! let mut pid = SpikingPid::new(spec)?;
//! let mut plant = FirstOrder::new(0.2, 1.0)?;
//!
//! let (dt, setpoint) = (1e-4, 1.0);
//! for _ in 0..30_000 {
//!     let u = pid.step(dt, setpoint - plant.y)?;
//!     plant.step(dt, u)?;
//! }
//!
//! // A proportional loop leaves a standing offset, and the offset has a closed form.
//! let predicted = plant.p_only_steady_state_error(setpoint, pid.kp());
//! assert!(((setpoint - plant.y) / predicted - 1.0).abs() < 0.01);
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```

