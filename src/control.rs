/// The Matsuoka neural oscillator: two mutually inhibiting units with adaptation.
///
/// From Matsuoka, *Sustained oscillations generated by mutually inhibiting neurons with
/// adaptation*, Biological Cybernetics 52:367–376, 1985, in the notation the robotics literature
/// uses (Williamson, *Rhythmic robot arm control using oscillators*, IROS 1998):
///
/// ```text
/// tau_r · x1' = −x1 − beta·v1 − w·y2 + s
/// tau_a · v1' = −v1 + y1                      y1 = max(0, x1)
/// tau_r · x2' = −x2 − beta·v2 − w·y1 + s
/// tau_a · v2' = −v2 + y2                      y2 = max(0, x2)
/// ```
///
/// `beta` and `w` are **dimensionless** in the paper and are kept dimensionless here; `x`, `v` and
/// `s` share one arbitrary unit which cancels out of everything the model is used for. The
/// conversion to a physical command happens at the boundary in [`Matsuoka::drive`], the same
/// policy [`crate::neuron::Izhikevich`] follows for its millivolt constants.
///
/// # The closed forms this is checked against
///
/// All four follow from the equations rather than from a figure, and they are the properties the
/// robotics literature relies on when it tunes a gait:
///
/// 1. **The symmetric equilibrium is exact**: `x1 = x2 = v1 = v2 = s/(1 + beta + w)`, which is
///    [`Matsuoka::symmetric_equilibrium`]. Started there, the oscillator never moves.
/// 2. **The period scales with the time constants.** Substituting `t → c·t` maps the system with
///    `(c·tau_r, c·tau_a)` exactly onto the system with `(tau_r, tau_a)`, so
///    `T(c·tau_r, c·tau_a) = c·T(tau_r, tau_a)`. You speed a gait up by scaling both constants,
///    and nothing else about the waveform changes.
/// 3. **The amplitude scales with the tonic drive and the period does not.** `max(0, ·)` is
///    positively homogeneous of degree one and every other term is linear, so scaling `s` by
///    `lambda > 0` scales the entire trajectory by `lambda` with the identical time course. This
///    is Matsuoka's own statement that the tonic input sets the amplitude while the time constants
///    set the frequency, and it is exact, not approximate.
/// 4. **The period at the onset of oscillation is closed form**, and it is the relationship
///    between the period and the time constants that this module grades a simulation against —
///    see [`Matsuoka::onset_period`] for the derivation and the measured convergence.
///
/// # What is **not** claimed
///
/// This review did not locate an **exact** closed-form expression for the period that holds at
/// arbitrary distance from the onset boundary. An **approximate** one is published, and this
/// module implements it as [`Matsuoka::harmonic_period`]: K. Matsuoka, *Analysis of a neural
/// oscillator*, Biological Cybernetics 104:297–304 (2011), doi:10.1007/s00422-011-0432-z, whose
/// abstract says it "shows two closed-form relations that express the frequency and amplitude of
/// the generated oscillation as functions of the parameters of the model. Although they are
/// derived based on a rough linear approximation, they accord with the result obtained by a
/// simulation considerably." The frequency relation equals [`Matsuoka::onset_period`] exactly at
/// `w = 1 + tau_r/tau_a` and, from `eps = 0.01` to `eps = 0.833` in the sweep tabulated there,
/// tracks the measured period far more closely — measured / `T_harm` is 1.0001 to 1.042 where
/// measured / `T0` is 1.0025 to 1.123. It is still an approximation: at that setting it is
/// slightly above the measurement right at onset, and once `w` passes `beta` it is the worse of
/// the two closed forms, falling further behind as `w` approaches `1 + beta`.
/// [`Matsuoka::measure_period`] therefore remains the measurement, and the margins by which
/// either closed form misses it are tabulated rather than hidden. The amplitude relation is not
/// implemented.
///
/// ⛔ **Correction.** This paragraph used to say that "Matsuoka's own analysis (and the 2011
/// follow-up …) works in the regime where exactly one unit is active at a time and still leaves a
/// transcendental crossing condition", and on that ground offered nothing away from onset. The
/// 2011 abstract quoted above says the opposite: closed-form relations from a linear
/// approximation. The 1985 paper is cited in this module for the model and for what its abstract
/// states about sustained oscillation — "Some sufficient conditions for that are given to three
/// types of neural networks" — and this review did not read its full text, so it does not
/// characterise that paper's method.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Matsuoka {
    /// Membrane time constant `tau_r`, seconds. The fast variable's rise time.
    pub tau_r: f64,
    /// Adaptation time constant `tau_a`, seconds. Conventionally several times `tau_r`; it is the
    /// slow variable whose fatigue ends each half-cycle.
    pub tau_a: f64,
    /// Adaptation strength `beta`, dimensionless. How hard a unit's own activity suppresses it.
    pub beta: f64,
    /// Mutual inhibition `w`, dimensionless. How hard each unit suppresses the other.
    pub w: f64,
    /// Tonic drive `s`, in the model's arbitrary unit. Sets the amplitude and not the frequency.
    pub s: f64,
    /// Membrane states `[x1, x2]`, model units.
    pub x: [f64; 2],
    /// Adaptation states `[v1, v2]`, model units.
    pub v: [f64; 2],
}

impl Matsuoka {
    /// Build with an asymmetric initial condition.
    ///
    /// The symmetric state `x = v = 0` is a fixed point of the equations, so an oscillator started
    /// there stays there forever. This constructor breaks the symmetry by putting `x1` at `+0.1·s`
    /// and `x2` at `−0.1·s`, deterministically and in the doc rather than in a comment, because a
    /// CPG that silently failed to start would look like a parameter problem.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `tau_r`, `tau_a` or `s`;
    /// [`ControlError::NotFinite`] for a non-finite `beta` or `w`.
    pub fn new(tau_r: f64, tau_a: f64, beta: f64, w: f64, s: f64) -> Result<Self, ControlError> {
        need_positive("tau_r", tau_r)?;
        need_positive("tau_a", tau_a)?;
        need_positive("s", s)?;
        need_finite("beta", beta)?;
        need_finite("w", w)?;
        Ok(Self { tau_r, tau_a, beta, w, s, x: [0.1 * s, -0.1 * s], v: [0.0, 0.0] })
    }

    /// Rectified outputs `[y1, y2] = [max(0, x1), max(0, x2)]`, model units.
    #[must_use]
    pub fn output(&self) -> [f64; 2] {
        [self.x[0].max(0.0), self.x[1].max(0.0)]
    }

    /// The antagonist difference `y1 − y2`, scaled into a physical command.
    ///
    /// **This is the unit boundary.** `scale` carries the units — newton-metres per model unit for
    /// a torque, radians per model unit for a position target — and the oscillator's own state
    /// stays dimensionless, so the paper's constants remain comparable to the paper.
    #[must_use]
    pub fn drive(&self, scale: f64) -> f64 {
        let y = self.output();
        scale * (y[0] - y[1])
    }

    fn deriv(&self, x: [f64; 2], v: [f64; 2]) -> ([f64; 2], [f64; 2]) {
        let y = [x[0].max(0.0), x[1].max(0.0)];
        let dx = [
            (-x[0] - self.beta * v[0] - self.w * y[1] + self.s) / self.tau_r,
            (-x[1] - self.beta * v[1] - self.w * y[0] + self.s) / self.tau_r,
        ];
        let dv = [(-v[0] + y[0]) / self.tau_a, (-v[1] + y[1]) / self.tau_a];
        (dx, dv)
    }

    /// Advance by `dt` seconds, fourth-order Runge-Kutta.
    ///
    /// The rectifier makes the vector field only piecewise smooth, so RK4's fourth-order accuracy
    /// degrades on the steps that straddle a corner. That is bounded rather than ignored: the
    /// scaling tests in this module run at a fixed `dt` and require the measured period to obey
    /// the exact scaling law to 0.1%, which a step size too coarse to resolve the corner fails.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`.
    pub fn step(&mut self, dt: f64) -> Result<(), ControlError> {
        need_positive("dt", dt)?;
        let (x0, v0) = (self.x, self.v);
        let (a1x, a1v) = self.deriv(x0, v0);
        let mid = |b: [f64; 2], d: [f64; 2], h: f64| [b[0] + h * d[0], b[1] + h * d[1]];
        let (a2x, a2v) = self.deriv(mid(x0, a1x, 0.5 * dt), mid(v0, a1v, 0.5 * dt));
        let (a3x, a3v) = self.deriv(mid(x0, a2x, 0.5 * dt), mid(v0, a2v, 0.5 * dt));
        let (a4x, a4v) = self.deriv(mid(x0, a3x, dt), mid(v0, a3v, dt));
        for i in 0..2 {
            self.x[i] += dt / 6.0 * (a1x[i] + 2.0 * a2x[i] + 2.0 * a3x[i] + a4x[i]);
            self.v[i] += dt / 6.0 * (a1v[i] + 2.0 * a2v[i] + 2.0 * a3v[i] + a4v[i]);
        }
        Ok(())
    }

    /// Run for `steps` steps of `dt`, returning both rectified outputs sampled every step.
    ///
    /// Refuses `steps` above [`MAX_RUN_STEPS`] rather than attempting the allocation.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`.
    pub fn run(&mut self, dt: f64, steps: usize) -> Result<[Vec<f64>; 2], ControlError> {
        check_run_length(steps)?;
        let mut a = Vec::with_capacity(steps);
        let mut b = Vec::with_capacity(steps);
        for _ in 0..steps {
            self.step(dt)?;
            let y = self.output();
            a.push(y[0]);
            b.push(y[1]);
        }
        Ok([a, b])
    }

    /// Run and measure the period of unit 1's output, discarding the first half as transient.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::TooFewCycles`] when
    /// the settled half of the run does not contain two complete cycles — which is the honest
    /// answer for a parameter set that does not oscillate, rather than a period of `f64::MAX`.
    pub fn measure_period(&mut self, dt: f64, steps: usize) -> Result<PeriodEstimate, ControlError> {
        let [a, _] = self.run(dt, steps)?;
        measure_period(&a[steps / 2..], dt)
    }

    /// The symmetric equilibrium, `x1 = x2 = v1 = v2 = s/(1 + beta + w)`, in model units.
    ///
    /// Both units active and equally so — the state the oscillator has to be *pushed off* before
    /// anything alternates. Substituting it into the equations gives zero on every line, so it is
    /// an exact fixed point of the continuous system and, because RK4 evaluates a vector field
    /// that is identically zero there, of the discretisation as well. That is why
    /// [`Matsuoka::new`] breaks the symmetry deliberately.
    ///
    /// `None` when `1 + beta + w <= 0`, which needs a negative `beta` or `w` and is outside the
    /// model's intended range; the value would be a negative "activity" and is refused instead.
    #[must_use]
    pub fn symmetric_equilibrium(&self) -> Option<f64> {
        let d = 1.0 + self.beta + self.w;
        if d > 0.0 { Some(self.s / d) } else { None }
    }

    /// The mutual inhibition at which oscillation begins: `w* = 1 + tau_r/tau_a`.
    #[must_use]
    pub fn onset_threshold(&self) -> f64 {
        1.0 + self.tau_r / self.tau_a
    }

    /// **The closed-form period at the onset of oscillation**, seconds:
    ///
    /// ```text
    /// T0 = 2π · sqrt( tau_r · tau_a / (1 + beta − w) )
    /// ```
    ///
    /// # Where it comes from
    ///
    /// At the symmetric equilibrium both units are active, so the rectifier is inactive and the
    /// system is exactly linear there. Write the **antisymmetric** mode `x1 = −x2 = ξ`,
    /// `v1 = −v2 = η` — the mode in which the two units move in opposition, which is the mode a
    /// gait lives in — and the tonic drive cancels, leaving
    ///
    /// ```text
    /// tau_r·ξ' = (w − 1)·ξ − beta·η
    /// tau_a·η' = ξ − η
    /// ```
    ///
    /// whose Jacobian has trace `(w − 1)/tau_r − 1/tau_a` and determinant
    /// `(1 + beta − w)/(tau_r·tau_a)`. The equilibrium loses stability when the trace turns
    /// positive, at `w = 1 + tau_r/tau_a` — which is [`Matsuoka::onset_threshold`] and the lower
    /// half of [`Matsuoka::may_oscillate`] — and at that instant the eigenvalues are purely
    /// imaginary with `omega² = ` the determinant. The expression above is `2π/omega`.
    ///
    /// # How well it holds, measured
    ///
    /// Exactly at onset, and increasingly optimistic above it across this table. Measured at
    /// `tau_r = 40 ms`, `tau_a = 240 ms`, `beta = 2.5`, with `w = w* + eps`:
    ///
    /// | `eps` | measured / `T0` | measured / `T_harm` |
    /// |-------|-----------------|---------------------|
    /// | 0.001 | 1.0000 | 0.9998 |
    /// | 0.01  | 1.0025 | 1.0001 |
    /// | 0.05  | 1.013  | 1.0012 |
    /// | 0.2   | 1.049  | 1.0075 |
    /// | 0.5   | 1.099  | 1.0214 |
    /// | 0.833 | 1.123  | 1.0420 |
    ///
    /// The third column is [`Matsuoka::harmonic_period`], Matsuoka's 2011 approximation, added
    /// when an audit found that the [`Matsuoka`] doc had misdescribed that paper; its doc says
    /// where the approximation stops being the better of the two.
    ///
    /// The ratio at `eps = 0.002` stays below 1.001 across five very different
    /// `(tau_r, tau_a, beta)` settings, which is the test in this module. Well inside the
    /// oscillating region the rectifier is engaged for most of each cycle and the linear mode is
    /// no longer the whole story — use [`Matsuoka::measure_period`] there and read this as a
    /// lower bound.
    ///
    /// `None` when `w >= 1 + beta`: above that the determinant is non-positive, the antisymmetric
    /// eigenvalues are real, and the mode grows without oscillating — a winner-take-all, not a
    /// rhythm.
    #[must_use]
    pub fn onset_period(&self) -> Option<f64> {
        let det = 1.0 + self.beta - self.w;
        if !(det > 0.0) {
            return None;
        }
        Some(TAU * (self.tau_r * self.tau_a / det).sqrt())
    }

    /// **Matsuoka's 2011 approximate period**, seconds, for use away from the onset boundary:
    ///
    /// ```text
    /// T_harm = 2π · tau_a · sqrt( tau_r·w / ((tau_r + tau_a)·beta − tau_r·w) )
    /// ```
    ///
    /// # Where it comes from
    ///
    /// K. Matsuoka, *Analysis of a neural oscillator*, Biological Cybernetics 104:297–304 (2011),
    /// doi:10.1007/s00422-011-0432-z, derives closed-form frequency and amplitude relations
    /// "based on a rough linear approximation" (abstract). That full text is closed access and
    /// this review did not read it, so the expression above is transcribed from the restatement
    /// in K. Muramatsu and H. Kori, *Bifurcation analysis of a two-neuron central pattern
    /// generator model for both oscillatory and convergent neuronal activities*, arXiv:2405.08409
    /// (2024), section III B, whose model is this one with `tau_x = tau_r`, `tau_y = tau_a`,
    /// `b = beta`, `a = w` and equal tonic drives. The restatement calls it an approximation
    /// "of `x_i` by a pure sinusoidal wave and the system … by a harmonic oscillator", exact at the
    /// onset boundary and "less accurate when `a` is sufficiently large". Only the frequency
    /// relation is implemented; the amplitude relation is not.
    ///
    /// # What it is checked against
    ///
    /// - **Algebra, with no simulation.** Setting `T_harm = T0` and clearing the square roots
    ///   leaves `tau_a·w² − (tau_a·(1 + beta) + tau_r)·w + (tau_r + tau_a)·beta = 0`, whose roots
    ///   are `w = 1 + tau_r/tau_a` and `w = beta`. So the two closed forms are **equal at onset**
    ///   — the restatement's "completely coincides … at the borderline" — and again at
    ///   `w = beta`; `T_harm` is the larger strictly between the two roots and the smaller beyond
    ///   them. The test checks both equalities to 1e-12 and both orderings at five settings,
    ///   which is a check on the transcription independent of any measurement.
    /// - **The measured period**, at `tau_r = 40 ms`, `tau_a = 240 ms`, `beta = 2.5`: the third
    ///   column of the table on [`Matsuoka::onset_period`]. From `eps = 0.01` to `eps = 0.833` it
    ///   is below the measurement and closes between 66% and 96% of the gap the onset form leaves
    ///   (1.0012 against 1.013 at `eps = 0.05`, 1.042 against 1.123 at `eps = 0.833`). Closer to
    ///   onset than that it is **above** the measurement — by 0.02% at `eps = 0.001` and 0.05% at
    ///   `eps = 0.002` — because the measured period follows `T0` there and `T_harm` rises about
    ///   twice as steeply with `w`. At `w = beta = 2.5` the two forms coincide, by the algebra
    ///   above, and measured / either is 1.1084; beyond it the approximation falls apart — at
    ///   `w = 3.25`, measured / `T_harm` is 1.8395 against 1.0759 for `T0`. That is the
    ///   restatement's "less accurate when `a` is sufficiently large", measured.
    ///   [`Matsuoka::measure_period`] remains the measurement.
    ///
    /// `None` where the expression has no meaning: `w <= 0` or `(tau_r + tau_a)·beta <= tau_r·w`,
    /// where the radicand is not a positive number, and `w >= 1 + beta`, where — as
    /// [`Matsuoka::onset_period`] says — the pair settles winner-take-all and there is no rhythm
    /// to approximate. Like [`Matsuoka::onset_period`] it does not ask whether this parameter set
    /// oscillates; [`Matsuoka::may_oscillate`] is that question.
    #[must_use]
    pub fn harmonic_period(&self) -> Option<f64> {
        let num = self.tau_r * self.w;
        let den = (self.tau_r + self.tau_a) * self.beta - num;
        if !(num > 0.0 && den > 0.0 && self.w < 1.0 + self.beta) {
            return None;
        }
        Some(TAU * self.tau_a * (num / den).sqrt())
    }

    /// Whether the symmetric equilibrium is unstable **in the antisymmetric mode**:
    /// `1 + tau_r/tau_a < w < 1 + beta`.
    ///
    /// Derived rather than transcribed — see [`Matsuoka::onset_period`] for the two-by-two
    /// Jacobian it comes from. The lower bound is trace `> 0`, the upper is determinant `> 0`.
    ///
    /// # ⚠ This is a local condition and sustained oscillation is a global question
    ///
    /// The equilibrium being unstable says the oscillator will *leave* it. Where it goes is a
    /// nonlinear question the linearisation cannot answer, and on a 400-point grid in
    /// `(w, beta, tau_a)` this predicate agreed with simulated sustained oscillation at **380 of
    /// 400 points**, with the 20 disagreements splitting into two mechanisms and **every one of
    /// them within 0.3 of one of the predicate's own two boundaries**:
    ///
    /// - **Predicate true, no rhythm** (5 points, all `w >= 2.2` and all within 0.3 of `1 + beta`):
    ///   inhibition strong enough that one unit wins permanently and the pair settles into a
    ///   winner-take-all fixed point instead of alternating.
    /// - **Predicate false, rhythm anyway** (15 points, all within 0.25 of `1 + tau_r/tau_a`): the
    ///   equilibrium is stable *and* a limit cycle coexists with it, so an initial condition far
    ///   enough out — which [`Matsuoka::new`] supplies on purpose — lands on the cycle.
    ///
    /// Treat it as a design rule with a margin, not as a decision procedure. The test that
    /// produced these numbers is in this module and is where a future change has to argue.
    #[must_use]
    pub fn may_oscillate(&self) -> bool {
        self.w > self.onset_threshold() && self.w < 1.0 + self.beta
    }
}

/// A spiking half-centre: two adapting populations, each inhibiting the other.
///
/// Brown's 1911 hypothesis, built from this crate's own [`crate::neuron::AdaptiveLif`]: each side
/// is driven by a tonic current, fatigues through its adapting threshold, and hyperpolarises the
/// other through an inhibitory synaptic trace. When the active side has adapted far enough that
/// its inhibition weakens, the silent side **escapes** and takes over. Nothing plans the
/// alternation; it is what the two mechanisms do together.
///
/// ⛔ **What this is, measured, rather than what the type name suggests.** At the
/// [`HalfCentre::locomotor`] parameters each side fires **one spike per alternation**, at a period
/// of 49 ms, with no interval below half the mean over 8 s — a two-neuron single-spike ping-pong,
/// not the alternating multi-spike bursts a locomotor half-centre produces. The mechanism is a
/// **release** half-centre, not an escape one: set the threshold-adaptation increment to zero and
/// the pair goes winner-take-all (501 spikes to 2), so the alternation is driven by the active
/// side's own fatigue weakening its inhibition. An escape half-centre needs the silent cell to
/// break through on its own — post-inhibitory rebound, an h-current — and
/// [`crate::neuron::AdaptiveLif`] has no such term. The first version of this doc said "escape"
/// and the test said "bursts"; both were wrong, and the test now pins the 49 ms and the one spike
/// per cycle so the description cannot drift from the model again. This implementation did not
/// locate a single canonical parameterisation, so the defaults are a tuning of this crate's own
/// neuron defaults rather than a transcription from a source.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HalfCentre {
    /// Left and right adapting neurons.
    pub side: [crate::neuron::AdaptiveLif; 2],
    /// Inhibitory traces, indexed by the side they inhibit.
    pub inhibition: [Trace; 2],
    /// Tonic drive current to both sides, amperes.
    pub drive_a: f64,
    /// Inhibitory synaptic weight, ampere-seconds per spike: a contralateral spike train at rate
    /// `r` removes `w_inh · r` amperes from the drive.
    pub w_inh: f64,
}

impl HalfCentre {
    /// The parameterisation the tests use: it alternates at **49 ms**, one spike per side per cycle.
    ///
    /// 20 ms membrane, 150 ms threshold adaptation stepping 1.5 mV per spike, 3 nA of tonic drive
    /// and a 30 ms inhibitory synapse of 4e-11 A·s per spike. What that weight removes from the
    /// partner: the inhibition trace peaks at 46 Hz after a spike, which is 1.85 nA, and averages
    /// 20.5 Hz over the run, which is 0.82 nA — the first version of this doc said 2.4 nA, a
    /// figure with no provenance that would need a sustained 60 Hz the model never reaches. The
    /// left side starts 3 mV depolarised, which is what breaks the symmetry — a perfectly
    /// symmetric half-centre fires **in phase** forever, and that is a property of the equations
    /// rather than a numerical accident.
    ///
    /// # Errors
    ///
    /// Never, in practice: every constant here is validated at compile time by being a literal.
    /// The signature returns `Result` because [`Trace::new`] does, and propagating is honest.
    pub fn locomotor() -> Result<Self, ControlError> {
        let lif = crate::neuron::Lif { t_ref: 2e-3, ..crate::neuron::Lif::default() };
        let mut left = crate::neuron::AdaptiveLif::new(lif, 150e-3, 1.5e-3);
        let right = crate::neuron::AdaptiveLif::new(lif, 150e-3, 1.5e-3);
        left.lif.v += 3e-3;
        Ok(Self {
            side: [left, right],
            inhibition: [Trace::new(30e-3)?, Trace::new(30e-3)?],
            drive_a: 3e-9,
            w_inh: 4e-11,
        })
    }

    /// Advance by `dt`, returning which sides spiked.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`.
    pub fn step(&mut self, dt: f64) -> Result<[bool; 2], ControlError> {
        use crate::neuron::Neuron;
        need_positive("dt", dt)?;
        let mut fired = [false; 2];
        for i in 0..2 {
            let inhibited = self.drive_a - self.w_inh * self.inhibition[i].value();
            fired[i] = self.side[i].step(dt, inhibited);
        }
        // Deposit AFTER both sides have stepped, so neither side sees the other's spike within the
        // same tick. Delivering in-tick would make the result depend on the order of the loop,
        // which is the silent kind of asymmetry that turns a symmetric model into a biased one.
        for i in 0..2 {
            self.inhibition[i].step(dt, u64::from(fired[1 - i]))?;
        }
        Ok(fired)
    }

    /// Run for `steps` steps of `dt`, returning each side's inhibition-trace envelope.
    ///
    /// The trace is returned rather than the raw spikes because a burst envelope is what a phase
    /// measurement needs; the trace on index `i` is driven by side `1 − i`, so the returned
    /// envelopes are **swapped back** to belong to the side that produced them.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`.
    pub fn run(&mut self, dt: f64, steps: usize) -> Result<HalfCentreRun, ControlError> {
        check_run_length(steps)?;
        let mut env = [Vec::with_capacity(steps), Vec::with_capacity(steps)];
        let mut spikes = [0u64; 2];
        for _ in 0..steps {
            let fired = self.step(dt)?;
            for i in 0..2 {
                spikes[i] += u64::from(fired[i]);
                // inhibition[1 - i] is fed by side i, so it is side i's own envelope.
                env[i].push(self.inhibition[1 - i].value());
            }
        }
        let [left, right] = env;
        Ok(HalfCentreRun { left, right, spikes, dt })
    }
}

/// What a [`HalfCentre`] run produced.
#[derive(Debug, Clone, PartialEq)]
pub struct HalfCentreRun {
    /// Left side's inhibition-trace envelope, hertz, one sample per step. At the `locomotor`
    /// parameters each side fires once per cycle, so this is a single-spike trace shape rather
    /// than a burst envelope; see the [`HalfCentre`] doc.
    pub left: Vec<f64>,
    /// Right side's envelope, as `left`.
    pub right: Vec<f64>,
    /// Spikes emitted by each side over the run.
    pub spikes: [u64; 2],
    /// Step size the run used, seconds.
    pub dt: f64,
}

impl HalfCentreRun {
    /// Phase of the right side relative to the left, radians in `[0, 2π)`, over the settled half.
    ///
    /// π is strict anti-phase — a walk. 0 is both sides bursting together, which is a hop.
    ///
    /// # Errors
    ///
    /// [`ControlError::TooFewCycles`] if either side did not complete two cycles;
    /// [`ControlError::PeriodMismatch`] if the two sides ran at different rates.
    pub fn phase(&self) -> Result<f64, ControlError> {
        let half = self.left.len() / 2;
        phase_difference(&self.left[half..], &self.right[half..], self.dt)
    }

    /// Period of the left side over the settled half.
    ///
    /// # Errors
    ///
    /// [`ControlError::TooFewCycles`] as [`measure_period`].
    pub fn period(&self) -> Result<PeriodEstimate, ControlError> {
        let half = self.left.len() / 2;
        measure_period(&self.left[half..], self.dt)
    }
}

