/// Parameters of a [`SpikingPid`], in the units the mapping to gains is stated in.
///
/// Build one of these, read [`SpikingPid::kp`], [`SpikingPid::ki`] and [`SpikingPid::kd`] to see
/// what classical controller it is, and tune whichever end you find easier to think in.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SpikingPidSpec {
    /// Encoder gain `g`, spikes per second per unit of error. Sets both the resolution and the
    /// energy: doubling it halves the quantisation step and doubles the spike rate.
    pub gain: f64,
    /// Proportional synapse time constant, seconds. Does not appear in `Kp` — the trace has unit
    /// DC gain — but it does set how much of the encoder's quantisation ripple reaches the plant.
    pub tau_p: f64,
    /// Proportional synaptic weight `a_p`, plant-input units × seconds per spike.
    pub a_p: f64,
    /// Integral synaptic weight `a_i`, plant-input units per spike. Zero disables integral action.
    pub a_i: f64,
    /// Derivative synaptic weight `a_d`, plant-input units × seconds per spike. Zero disables it.
    pub a_d: f64,
    /// Fast arm of the derivative synapse, seconds. Must be strictly below `tau_slow`.
    pub tau_fast: f64,
    /// Slow arm of the derivative synapse, seconds.
    pub tau_slow: f64,
    /// Actuator saturation, plant-input units. The command is held inside `±u_limit` and the
    /// integrator stops accumulating while the command is saturated — textbook anti-windup, here
    /// because without it a rate-limited plant makes the integral term run away during a large
    /// step and then overshoot by the amount it ran away.
    pub u_limit: f64,
}

impl SpikingPidSpec {
    /// A proportional-only controller: encoder gain `g`, classical gain `kp`, synapse `tau_p`.
    ///
    /// `a_p` is solved from `Kp = a_p · g`, so the spec you get back reports exactly the `kp` you
    /// asked for. The derivative arms are given distinct defaults so the spec validates, with
    /// `a_d = 0` leaving the term disabled.
    #[must_use]
    pub fn proportional(gain: f64, kp: f64, tau_p: f64) -> Self {
        Self {
            gain,
            tau_p,
            a_p: kp / gain,
            a_i: 0.0,
            a_d: 0.0,
            tau_fast: 1e-3,
            tau_slow: 10e-3,
            u_limit: f64::INFINITY,
        }
    }

    /// A controller with all three terms, specified by the **classical** gains.
    ///
    /// `a_p = Kp/g`, `a_i = Ki/g`, `a_d = Kd / (g · (tau_slow − tau_fast))` — the mapping in the
    /// module doc, solved the other way round.
    #[must_use]
    pub fn from_gains(
        gain: f64,
        kp: f64,
        ki: f64,
        kd: f64,
        tau_p: f64,
        tau_fast: f64,
        tau_slow: f64,
    ) -> Self {
        Self {
            gain,
            tau_p,
            a_p: kp / gain,
            a_i: ki / gain,
            a_d: kd / (gain * (tau_slow - tau_fast)),
            tau_fast,
            tau_slow,
            u_limit: f64::INFINITY,
        }
    }
}

/// A PID controller whose only internal signal is a spike train.
///
/// # The mapping, derived
///
/// The error `e` drives a [`SignedEncoder`] at gain `g`, so the net spike rate — positive channel
/// minus negative channel — is exactly `g · e`.
///
/// **Proportional.** A [`Trace`] has unit DC gain in hertz, so its steady value under that rate is
/// `g · e`, and `u_p = a_p · (x⁺ − x⁻)` has mean `a_p · g · e`. Hence `Kp = a_p · g`.
///
/// **Integral.** The accumulator adds `a_i` per positive spike and subtracts it per negative one,
/// never decaying. Its rate of change is therefore `a_i · g · e`, which is the definition of
/// `u_i = Ki ∫ e dt` with `Ki = a_i · g`. A synapse with an infinite time constant *is* an
/// integrator; that is the whole of the correspondence.
///
/// **Derivative.** Two traces with unit DC gain subtract to a filter with **zero** DC gain. Feed a
/// ramp `r(t) = c·t` into a first-order low-pass of time constant `tau` and its asymptotic output
/// is `c·(t − tau)` — it lags by exactly `tau`. The difference of a fast and a slow arm is
/// therefore exactly `c · (tau_slow − tau_fast)`, and with `c = g · de/dt`,
/// `Kd = a_d · g · (tau_slow − tau_fast)`. This is the identity [`SpikingPid`]'s ramp test checks.
///
/// # What the mapping is not
///
/// It is a statement about **means**. The instantaneous command carries the encoder's quantisation
/// ripple, whose size is `a_p / tau_p` per spike on the P branch; a plant slower than `tau_p`
/// filters it away and a plant faster than `tau_p` does not. The closed-form steady-state error in
/// [`FirstOrder::p_only_steady_state_error`] is exact for the mean and approached by the
/// simulation as the ripple shrinks, which is what the tests measure rather than assume.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SpikingPid {
    spec: SpikingPidSpec,
    enc: SignedEncoder,
    p_pos: Trace,
    p_neg: Trace,
    d_fast_pos: Trace,
    d_fast_neg: Trace,
    d_slow_pos: Trace,
    d_slow_neg: Trace,
    integral: f64,
    elapsed_s: f64,
    ticks: u64,
}

impl SpikingPid {
    /// Build and validate.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `gain`, `tau_p`, `tau_fast`, `tau_slow` or
    /// `u_limit`; [`ControlError::NotFinite`] for a non-finite weight;
    /// [`ControlError::NotOrdered`] unless `tau_fast < tau_slow` — except that a spec built by
    /// [`SpikingPidSpec::from_gains`] with `tau_fast == tau_slow` and a non-zero `kd` has an
    /// infinite `a_d`, and the `NotFinite` check runs first.
    pub fn new(spec: SpikingPidSpec) -> Result<Self, ControlError> {
        need_positive("gain", spec.gain)?;
        need_positive("tau_p", spec.tau_p)?;
        need_positive("tau_fast", spec.tau_fast)?;
        need_positive("tau_slow", spec.tau_slow)?;
        need_finite("a_p", spec.a_p)?;
        need_finite("a_i", spec.a_i)?;
        need_finite("a_d", spec.a_d)?;
        // `u_limit` may be infinite — that is "no actuator limit" — but it may not be zero,
        // negative or NaN. A negative limit would make the two clamp bounds cross, which is the
        // shape of a defect this crate has shipped before: `f64::clamp` panics when they do.
        if !(spec.u_limit > 0.0) {
            return Err(ControlError::NotPositive { what: "u_limit", value: spec.u_limit });
        }
        if !(spec.tau_fast < spec.tau_slow) {
            return Err(ControlError::NotOrdered { fast: spec.tau_fast, slow: spec.tau_slow });
        }
        Ok(Self {
            spec,
            enc: SignedEncoder::new(spec.gain)?,
            p_pos: Trace::new(spec.tau_p)?,
            p_neg: Trace::new(spec.tau_p)?,
            d_fast_pos: Trace::new(spec.tau_fast)?,
            d_fast_neg: Trace::new(spec.tau_fast)?,
            d_slow_pos: Trace::new(spec.tau_slow)?,
            d_slow_neg: Trace::new(spec.tau_slow)?,
            integral: 0.0,
            elapsed_s: 0.0,
            ticks: 0,
        })
    }

    /// The classical proportional gain this controller is equivalent to: `a_p · g`.
    #[must_use]
    pub fn kp(&self) -> f64 {
        self.spec.a_p * self.spec.gain
    }

    /// The classical integral gain, per second: `a_i · g`.
    #[must_use]
    pub fn ki(&self) -> f64 {
        self.spec.a_i * self.spec.gain
    }

    /// The classical derivative gain, seconds: `a_d · g · (tau_slow − tau_fast)`.
    #[must_use]
    pub fn kd(&self) -> f64 {
        self.spec.a_d * self.spec.gain * (self.spec.tau_slow - self.spec.tau_fast)
    }

    /// The spec this controller was built from.
    #[must_use]
    pub fn spec(&self) -> SpikingPidSpec {
        self.spec
    }

    /// Advance by `dt` seconds under error `e`, returning the command in plant-input units.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::NotFinite`] for a
    /// non-finite `e`.
    pub fn step(&mut self, dt: f64, e: f64) -> Result<f64, ControlError> {
        need_positive("dt", dt)?;
        need_finite("error", e)?;
        let (np, nn) = self.enc.step(dt, e)?;

        let p = self.spec.a_p * (self.p_pos.step(dt, np)? - self.p_neg.step(dt, nn)?);

        let fast = self.d_fast_pos.step(dt, np)? - self.d_fast_neg.step(dt, nn)?;
        let slow = self.d_slow_pos.step(dt, np)? - self.d_slow_neg.step(dt, nn)?;
        // fast − slow is the high-pass: a ramp leaves each arm lagging by its own tau, so the
        // difference is the ramp slope times (tau_slow − tau_fast).
        let d = self.spec.a_d * (fast - slow);

        // Conditional integration: accumulate, and if the command saturates in the direction the
        // integral is pushing, take the accumulation back. This is the cheapest correct
        // anti-windup and it leaves the unsaturated case bit-identical to no anti-windup at all.
        let before = self.integral;
        if np > 0 || nn > 0 {
            self.integral += self.spec.a_i * (np as f64 - nn as f64);
        }
        let raw = p + self.integral + d;
        let u = clamp_sym(raw, self.spec.u_limit);
        if u != raw && (u - raw).signum() == (before - self.integral).signum() {
            self.integral = before;
        }

        self.elapsed_s += dt;
        self.ticks += 1;
        Ok(clamp_sym(p + self.integral + d, self.spec.u_limit))
    }

    /// Spikes the error encoder has emitted since construction or the last reset.
    #[must_use]
    pub fn spikes(&self) -> u64 {
        self.enc.spikes()
    }

    /// Seconds of control simulated since construction or the last reset.
    #[must_use]
    pub fn elapsed_s(&self) -> f64 {
        self.elapsed_s
    }

    /// The energy account for this run: one error population of two cells, three synapses per
    /// spike, and the tick count a clocked implementation would have paid for.
    ///
    /// `mode` decides whether the idle membrane updates are charged: a clocked implementation pays
    /// `2 · ticks` of them whatever the error is, and an event-driven one pays none while the
    /// error is zero. That difference is the architecture's entire claim, and this is where it
    /// becomes a number instead of an adjective.
    #[must_use]
    pub fn budget(&self, mode: Mode) -> ControlBudget {
        ControlBudget::new(self.spikes(), self.elapsed_s, self.ticks, 2, 3, mode)
    }

    /// Return every trace, the integrator, the encoder accumulators and the counters to rest.
    pub fn reset(&mut self) {
        self.enc.reset();
        for t in [
            &mut self.p_pos,
            &mut self.p_neg,
            &mut self.d_fast_pos,
            &mut self.d_fast_neg,
            &mut self.d_slow_pos,
            &mut self.d_slow_neg,
        ] {
            t.reset();
        }
        self.integral = 0.0;
        self.elapsed_s = 0.0;
        self.ticks = 0;
    }
}

/// Clamp `x` into `[−limit, limit]` without `f64::clamp`.
///
/// `f64::clamp` panics when its bounds cross, and this crate has shipped a clamp whose bounds
/// crossed on parameters its own constructor accepted. `limit` is validated positive at
/// construction; this form cannot panic even if that validation is ever weakened.
fn clamp_sym(x: f64, limit: f64) -> f64 {
    if x > limit {
        limit
    } else if x < -limit {
        -limit
    } else {
        x
    }
}

