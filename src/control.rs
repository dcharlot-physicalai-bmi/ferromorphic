/// A first-order synaptic trace normalised to **unit DC gain in hertz**.
///
/// `tau · dx/dt = −x`, with each spike depositing `1 / tau`. Under a steady spike rate `r` the
/// time-average of `x` is exactly `r`: each spike contributes an area of `(1/tau) · tau = 1`, and
/// `r` of them arrive per second. That normalisation is what lets [`SpikingPid`] state its gains
/// in closed form rather than fitting them.
///
/// The decay is exponential and exact over the step, for the reason [`crate::neuron::Lif`] gives:
/// forward Euler on this equation has an error growing with `dt / tau` and goes unstable above
/// `dt = 2 tau`, which a user coarsening the step to save energy would meet without warning.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Trace {
    /// Decay time constant, seconds. Strictly positive.
    pub tau: f64,
    /// Current value, hertz — a filtered firing rate, not a voltage.
    pub x: f64,
}

impl Trace {
    /// Build with a decay time constant in seconds, starting empty.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for a `NaN` or infinite `tau`, [`ControlError::NotPositive`] for
    /// a zero or negative one.
    pub fn new(tau: f64) -> Result<Self, ControlError> {
        need_positive("tau", tau)?;
        Ok(Self { tau, x: 0.0 })
    }

    /// Decay by `dt` seconds, then deposit `n` spikes' worth of charge.
    ///
    /// Order matters and is stated: a spike arriving during a step is not decayed by that step's
    /// own interval, which keeps the trace's response to a single spike exactly `exp(−t/tau)/tau`
    /// measured from the spike.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`.
    pub fn step(&mut self, dt: f64, n: u64) -> Result<f64, ControlError> {
        need_positive("dt", dt)?;
        self.x *= (-dt / self.tau).exp();
        if n > 0 {
            self.x += n as f64 / self.tau;
        }
        Ok(self.x)
    }

    /// Current value, hertz.
    #[must_use]
    pub fn value(&self) -> f64 {
        self.x
    }

    /// Empty the trace.
    pub fn reset(&mut self) {
        self.x = 0.0;
    }
}

