/// A lossless sigma-delta spike encoder: **exactly** `floor(gain · x · t)` spikes in `t` seconds.
///
/// A non-leaky accumulator charged at `gain · max(x, 0)` spikes per second, emitting a spike and
/// **subtracting one** each time it passes unity. Half-wave rectified, because a spike has no
/// sign; [`SignedEncoder`] is the push-pull pair that carries one.
///
/// # The invariant, and why it is worth the departure from the neuron models
///
/// Starting from `acc = 0` and stepping with any partition of `[0, t]`, the emitted count is
/// `floor(gain · x · t)` for constant `x ≥ 0` — exactly, to floating-point rounding, and
/// independently of the time step. Reset-to-zero would instead discard the remainder at every
/// spike, so the realised rate would fall below `gain · x` by an amount that depends on `dt`, and
/// every closed-form check in this module would acquire a fudge factor.
///
/// This is therefore **not** a model of a neuron and deliberately does not implement
/// [`crate::neuron::Neuron`]. See the module doc for the equivalence Yoon (2017) established
/// between leaky integrate-and-fire and asynchronous pulse sigma-delta modulation.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SigmaDeltaEncoder {
    /// Spikes per second per unit of input, at unit input. Strictly positive, finite.
    pub gain: f64,
    /// Accumulated charge in units of the threshold; in `[0, 1)` after every successful step. A
    /// refused step (see [`SigmaDeltaEncoder::step`]) empties it, so the encoder stays usable.
    pub acc: f64,
    /// Spikes emitted since construction or the last [`SigmaDeltaEncoder::reset`].
    pub spikes: u64,
}

impl SigmaDeltaEncoder {
    /// Build with an encoder gain in spikes per second per unit of input.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for a `NaN` or infinite `gain`, [`ControlError::NotPositive`]
    /// for a zero or negative one: the finiteness screen runs first, so an infinite gain is named
    /// for what it is rather than slipping through a bare `> 0.0` test.
    pub fn new(gain: f64) -> Result<Self, ControlError> {
        need_positive("gain", gain)?;
        Ok(Self { gain, acc: 0.0, spikes: 0 })
    }

    /// Advance by `dt` seconds under input `x`, returning the spikes emitted **in this step**.
    ///
    /// More than one is possible and is not an error: a step long enough to hold several spikes
    /// emits several, which is what keeps the count independent of `dt`.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::NotFinite`] for a
    /// non-finite `x`, for a step whose charge is not finite or would emit more than `u64::MAX`
    /// spikes, and for a running total that would exceed `u64::MAX`. On any of those the
    /// accumulator is emptied rather than left holding `inf` or `NaN`.
    pub fn step(&mut self, dt: f64, x: f64) -> Result<u64, ControlError> {
        need_positive("dt", dt)?;
        need_finite("encoder input", x)?;
        self.acc += self.gain * x.max(0.0) * dt;
        if self.acc < 1.0 {
            return Ok(0);
        }
        let n = self.acc.floor();
        // ⛔ ONE CALL CAN DO IT. The comment that stood here said a run long enough to overflow
        // `u64` would take 1e11 years at 1 GHz. `step(1.0, 1e300)` at a gain of 1e6 does it in
        // one: the cast saturated silently in release, the add panicked in debug, and with an
        // infinite product `acc` became `inf - inf = NaN` and the encoder was dead without
        // saying so. `NaN` fails the comparison below, so it is refused by the same line.
        if !(n < U64_EXACT) {
            self.acc = 0.0;
            return Err(ControlError::NotFinite { what: "spikes in one step (past u64)", value: n });
        }
        let count = n as u64;
        let Some(total) = self.spikes.checked_add(count) else {
            self.acc = 0.0;
            return Err(ControlError::NotFinite { what: "total spike count (past u64)", value: n });
        };
        self.acc -= n;
        self.spikes = total;
        Ok(count)
    }

    /// The exact spike count this encoder emits in `t` seconds at constant input `x`, from rest.
    ///
    /// The closed form the simulator is checked against: `floor(gain · x · t)`, and `Some(0)` for
    /// `x ≤ 0` because the encoder is rectified.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `t`; [`ControlError::NotFinite`] for a
    /// non-finite `x` or a count that is not finite or does not fit in `u64` — the same refusal
    /// [`SigmaDeltaEncoder::step`] makes, so the closed form and the simulator agree on what
    /// they will not count.
    pub fn spikes_in(&self, x: f64, t: f64) -> Result<u64, ControlError> {
        need_positive("t", t)?;
        need_finite("encoder input", x)?;
        let n = (self.gain * x.max(0.0) * t).floor();
        if !(n < U64_EXACT) {
            return Err(ControlError::NotFinite { what: "expected spike count (past u64)", value: n });
        }
        Ok(n as u64)
    }

    /// Instantaneous firing rate at input `x`, hertz: `gain · max(x, 0)`.
    #[must_use]
    pub fn rate(&self, x: f64) -> f64 {
        self.gain * x.max(0.0)
    }

    /// Empty the accumulator and the spike counter.
    pub fn reset(&mut self) {
        self.acc = 0.0;
        self.spikes = 0;
    }
}

/// `2^64` as an `f64`: a non-negative `f64` strictly below it converts to `u64` exactly.
const U64_EXACT: f64 = 18_446_744_073_709_551_616.0;

/// The most steps [`Matsuoka::run`] and [`HalfCentre::run`] will record: `2^25`, which is 537 MB
/// of `f64` samples across the two returned traces. Both take a caller-supplied `usize` and used
/// to hand it straight to `Vec::with_capacity`, the one unguarded allocation in the module.
pub const MAX_RUN_STEPS: usize = 1 << 25;

fn check_run_length(steps: usize) -> Result<(), ControlError> {
    if steps > MAX_RUN_STEPS {
        return Err(ControlError::NotFinite { what: "steps (past MAX_RUN_STEPS)", value: steps as f64 });
    }
    Ok(())
}

/// A push-pull pair of encoders: one for the positive part of a signal, one for the negative.
///
/// A spike carries no sign, so a signed quantity needs two channels. This is how the nervous
/// system does it too — agonist and antagonist, ON and OFF retinal ganglion cells — and it is why
/// a spiking controller at its setpoint is silent on **both** channels rather than balanced
/// between two busy ones.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SignedEncoder {
    /// Channel driven by `max(x, 0)`.
    pub pos: SigmaDeltaEncoder,
    /// Channel driven by `max(−x, 0)`.
    pub neg: SigmaDeltaEncoder,
}

impl SignedEncoder {
    /// Build both channels with the same gain, in spikes per second per unit of input.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for a `NaN` or infinite `gain`, [`ControlError::NotPositive`]
    /// for a zero or negative one: the finiteness screen runs first, so an infinite gain is named
    /// for what it is rather than slipping through a bare `> 0.0` test.
    pub fn new(gain: f64) -> Result<Self, ControlError> {
        Ok(Self { pos: SigmaDeltaEncoder::new(gain)?, neg: SigmaDeltaEncoder::new(gain)? })
    }

    /// Advance both channels by `dt` under signed input `x`, returning `(positive, negative)`.
    ///
    /// Exactly one of the two can be non-zero in a step of a constant sign, because the channels
    /// are rectified complements.
    ///
    /// # Errors
    ///
    /// As [`SigmaDeltaEncoder::step`].
    pub fn step(&mut self, dt: f64, x: f64) -> Result<(u64, u64), ControlError> {
        Ok((self.pos.step(dt, x)?, self.neg.step(dt, -x)?))
    }

    /// Total spikes emitted on both channels.
    #[must_use]
    pub fn spikes(&self) -> u64 {
        self.pos.spikes + self.neg.spikes
    }

    /// Clear both accumulators and both counters.
    pub fn reset(&mut self) {
        self.pos.reset();
        self.neg.reset();
    }
}

