    /// ⭐ (e) THE CASE THE WHOLE ARCHITECTURE IS FOR. A controller whose error is zero emits
    /// **exactly zero** spikes, and the pendulum it is holding does not move at all — bit for bit,
    /// not approximately. The comparison run with a non-zero setpoint shows the test can fail.
    #[test]
    fn a_controller_at_its_setpoint_emits_the_minimum_possible_spikes() {
        let spec = SpikingPidSpec::from_gains(20_000.0, 2.0, 5.0, 0.05, 5e-3, 2e-3, 20e-3);
        let dt = 1e-4;
        let steps = 50_000; // 5 s

        // Hanging straight down with the setpoint at the bottom: an exact fixed point.
        let mut pid = SpikingPid::new(spec).unwrap();
        let mut pend = Pendulum::new(0.5, 1.0).unwrap();
        for _ in 0..steps {
            let torque = pid.step(dt, 0.0 - pend.theta).unwrap();
            pend.step(dt, torque).unwrap();
        }
        assert_eq!(pid.spikes(), 0, "a held setpoint cost spikes");
        assert!(pend.theta == 0.0 && pend.omega == 0.0, "the plant moved: {pend:?}");
        let budget = pid.budget(Mode::EventDriven);
        assert_eq!(budget.spikes_per_second(), Some(0.0));
        let led = budget.to_ledger();
        assert_eq!(led.syn_ops, 0);
        assert_eq!(led.neuron_updates_driven, 0);
        assert_eq!(led.idle_fraction(), None, "an event-driven run did nothing at all");

        // The same controller, one degree away: now it costs something.
        let mut pid2 = SpikingPid::new(spec).unwrap();
        let mut pend2 = Pendulum::new(0.5, 1.0).unwrap();
        for _ in 0..steps {
            let torque = pid2.step(dt, 0.0_f64.to_radians() + 0.2 - pend2.theta).unwrap();
            pend2.step(dt, torque).unwrap();
        }
        assert!(pid2.spikes() > 0, "a controller with work to do emitted nothing");
        assert!(
            pid2.budget(Mode::EventDriven).spikes_per_second().unwrap() > 1.0,
            "the comparison case is indistinguishable from the held one"
        );
        // ⛔ THE LEDGER, ASSERTED ON A RUN THAT DID SOMETHING. `budget()` says three synapses per
        // spike — P, I and D on one train, the module's central architectural claim — and
        // `to_ledger` says every spike is one driven update and one routed spike. Neither was
        // checked: `2, 1` in place of `2, 3`, `driven = 0` and `spikes_out: 0` all passed, because
        // the only ledger assertions were on the held run where every count is zero anyway.
        let n = pid2.spikes();
        let led2 = pid2.budget(Mode::Clocked).to_ledger();
        assert_eq!(led2.syn_ops, 3 * n, "three synapses per spike");
        assert_eq!(led2.syn_fetches, 3 * n);
        assert_eq!(led2.neuron_updates_driven, n, "one driven update per spike");
        assert_eq!(led2.spikes_out, n, "one routed spike per spike");
        assert_eq!(led2.neuron_updates_idle, 2 * steps as u64 - n);
        assert_eq!(led2.neuron_updates(), 2 * steps as u64);
        let ev2 = pid2.budget(Mode::EventDriven).to_ledger();
        assert_eq!((ev2.neuron_updates_idle, ev2.neuron_updates_driven, ev2.syn_ops), (0, n, 3 * n));
        assert!(
            ev2.idle_fraction() == Some(0.0),
            "an event-driven run has no idle updates: {:?}",
            ev2.idle_fraction()
        );

        // ⛔ And the clocked implementation pays for every one of those idle ticks. This is the
        // number the event-driven argument is about, and for a held setpoint it is exactly 1.0.
        let clocked = pid.budget(Mode::Clocked).to_ledger();
        assert_eq!(clocked.neuron_updates(), 2 * steps as u64);
        assert_eq!(clocked.idle_fraction(), Some(1.0));
    }

