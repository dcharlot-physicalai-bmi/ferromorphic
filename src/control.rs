/// Why a control operation could not be performed.
///
/// Every variant names the offending quantity. A controller that clamped a bad parameter into
/// range would produce a plant trajectory that looks like a tuning problem rather than a bug.
#[derive(Debug, Clone, PartialEq)]
pub enum ControlError {
    /// A supplied number was `NaN` or infinite.
    NotFinite {
        /// Which quantity, e.g. `"dt"`, `"error"`, `"torque"`.
        what: &'static str,
        /// The value as supplied, for the message.
        value: f64,
    },
    /// A quantity that must be strictly positive was zero or negative.
    NotPositive {
        /// Which quantity, e.g. `"tau"`, `"gain"`.
        what: &'static str,
        /// The value as supplied.
        value: f64,
    },
    /// Two time constants that must be distinct and ordered were not.
    ///
    /// The derivative synapse is a fast trace minus a slow one; equal time constants make it
    /// identically zero, which is a silently disabled D term rather than an error.
    NotOrdered {
        /// The value required to be smaller.
        fast: f64,
        /// The value required to be larger.
        slow: f64,
    },
    /// A signal did not contain enough complete cycles to measure anything.
    TooFewCycles {
        /// Threshold crossings found in the samples supplied.
        found: usize,
        /// Crossings needed before a period is reported.
        needed: usize,
    },
    /// Two signals whose relative phase was asked for do not share a period.
    ///
    /// Returned rather than a phase, because the phase of two signals at different frequencies is
    /// a number that drifts and will still plot.
    PeriodMismatch {
        /// Period measured on the first signal, seconds.
        a_s: f64,
        /// Period measured on the second signal, seconds.
        b_s: f64,
    },
    /// An angle outside the range where the quantity asked for is defined.
    AngleOutOfRange {
        /// The angle supplied, radians.
        theta: f64,
        /// The exclusive bound it had to stay inside, radians.
        limit: f64,
    },
    /// A population-coding call underneath this one refused. Carries its reason verbatim.
    Coding(CodeError),
}

impl fmt::Display for ControlError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotFinite { what, value } => write!(f, "{what} was not finite ({value})"),
            Self::NotPositive { what, value } => {
                write!(f, "{what} must be strictly positive, got {value}")
            }
            Self::NotOrdered { fast, slow } => write!(
                f,
                "the derivative synapse needs tau_fast < tau_slow, got {fast} and {slow}; equal \
                 time constants make the D term identically zero"
            ),
            Self::TooFewCycles { found, needed } => {
                write!(f, "found {found} threshold crossings, need {needed} to measure a period")
            }
            Self::PeriodMismatch { a_s, b_s } => {
                write!(f, "signals have different periods ({a_s} s and {b_s} s); no fixed phase")
            }
            Self::AngleOutOfRange { theta, limit } => {
                write!(f, "angle {theta} rad is outside the open interval of half-width {limit}")
            }
            Self::Coding(e) => write!(f, "population coding refused: {e}"),
        }
    }
}

impl std::error::Error for ControlError {}

impl From<CodeError> for ControlError {
    fn from(e: CodeError) -> Self {
        Self::Coding(e)
    }
}

fn need_finite(what: &'static str, value: f64) -> Result<(), ControlError> {
    if value.is_finite() { Ok(()) } else { Err(ControlError::NotFinite { what, value }) }
}

fn need_positive(what: &'static str, value: f64) -> Result<(), ControlError> {
    need_finite(what, value)?;
    // `!(value > 0.0)` rather than `value <= 0.0` so a NaN that somehow survived is rejected; see
    // the crate's `neg_cmp_op_on_partial_ord` allow and the reason given with it.
    if !(value > 0.0) { Err(ControlError::NotPositive { what, value }) } else { Ok(()) }
}

