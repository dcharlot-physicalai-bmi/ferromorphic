    /// ⭐ THE WHOLE CONTROLLER AGAINST A CLOSED FORM, D term included. Driven open-loop with a
    /// ramp error `e(t) = c·t`, the command has an exact asymptote:
    ///
    /// ```text
    /// u(t) = Kp·c·(t − tau_p)  +  Kd·c
    /// ```
    ///
    /// The `tau_p` is the proportional trace's own lag on a ramp; the `Kd·c` is the derivative
    /// term, constant because the error's slope is constant. This is the test that would catch a
    /// D branch wired with the wrong sign, scaled by the wrong pair of time constants, or dropped
    /// altogether — none of which the gain getters or the closed-loop tests can see.
    #[test]
    fn the_full_command_matches_its_ramp_closed_form_including_the_derivative_term() {
        let (g, kp, kd) = (20_000.0, 0.5, 1.0);
        // The traces' deposit-after-decay convention biases the derivative branch high by
        // `Kd·c·t·dt/(2·tau_fast·tau_slow)` — the ONE place in this module where that artefact is
        // amplified, because the encoder rate on a ramp reaches 114 kHz. At these constants it is
        // 3.6e-3 of an answer near 5.77, so it sits a factor of three inside the tolerance and is
        // named here rather than absorbed into a looser one.
        let (tau_p, tau_f, tau_s) = (50e-3, 20e-3, 200e-3);
        let c = 3.0; // error units per second
        let dt = 5e-6;
        let steps = 400_000; // 2 s; ten slow-arm time constants, so nothing transient is left

        let measure = |a_d_on: bool, c: f64| {
            let mut spec = SpikingPidSpec::from_gains(g, kp, 0.0, kd, tau_p, tau_f, tau_s);
            if !a_d_on {
                spec.a_d = 0.0;
            }
            let mut pid = SpikingPid::new(spec).unwrap();
            let mut sum = 0.0;
            let mut n = 0usize;
            for i in 0..steps {
                let t = i as f64 * dt;
                let u = pid.step(dt, c * t).unwrap();
                if i >= steps - 40_000 {
                    sum += u;
                    n += 1;
                }
            }
            (sum / n as f64, pid.elapsed_s())
        };

        // u is linear in t, so its mean over the window equals its value at the window's midpoint.
        let t_mid = (steps as f64 - 20_000.5) * dt;
        let (with_d, elapsed) = measure(true, c);
        let want = kp * c * (t_mid - tau_p) + kd * c;
        assert!((with_d / want - 1.0).abs() < 2e-3, "command {with_d}, closed form {want}");
        assert!((elapsed - steps as f64 * dt).abs() < 1e-9, "elapsed_s drifted: {elapsed}");

        // ANTI-VACUITY: turn the D term off and the answer must move by Kd·c and no more.
        let (without_d, _) = measure(false, c);
        let want_p = kp * c * (t_mid - tau_p);
        assert!((without_d / want_p - 1.0).abs() < 2e-3, "P-only {without_d}, want {want_p}");
        assert!(
            ((with_d - without_d) / (kd * c) - 1.0).abs() < 0.02,
            "the D term contributed {} where the closed form says {}",
            with_d - without_d,
            kd * c
        );
        // And tau_p really is the lag: without it the prediction is out by Kp·c·tau_p, which must
        // be larger than the tolerance or this test does not see the lag at all.
        let no_lag = kp * c * t_mid + kd * c;
        assert!((with_d / no_lag - 1.0).abs() > 2e-3, "the ramp lag is below the tolerance");

        // ⛔ THE NEGATIVE RAMP drives the `d_fast_neg`/`d_slow_neg` arms and the negative P
        // channel, which nothing else in the suite reaches; with them deleted the D contribution
        // here was +0.000000 against a closed form of -3. The controller is antisymmetric to the
        // last bit, because every arm is `positive trace - negative trace` and the two swap roles.
        let (with_d_neg, _) = measure(true, -c);
        assert!(
            (with_d_neg / -want - 1.0).abs() < 2e-3,
            "negative ramp: command {with_d_neg}, closed form {}",
            -want
        );
        assert!(
            (with_d_neg + with_d).abs() <= 1e-12 * with_d.abs(),
            "u(-c) = {with_d_neg} is not the negative of u(+c) = {with_d}"
        );
    }

