/// A scalar, time-invariant Kalman filter: `x' = a·x + w`, `z = x + v`.
///
/// # What it is for
///
/// The steady-state gain of this problem has a **closed form**, which is what makes it worth
/// having in a crate that refuses to verify against its own output. The scalar discrete algebraic
/// Riccati equation
///
/// ```text
/// p = a²·p·R/(p + R) + Q        (p the prior variance, K = p/(p + R))
/// ```
///
/// rearranges to `p² + p·(R − a²R − Q) − Q·R = 0`, whose positive root is
///
/// ```text
/// p = [ (a²R + Q − R) + sqrt( (R − a²R − Q)² + 4QR ) ] / 2
/// ```
///
/// Three special cases check it without a simulation at all: `a = 1, Q = 0` gives `p = 0` and
/// `K = 0` (a constant observed forever, where the running mean eventually ignores new data);
/// `R = 0` gives `p = Q` and `K = 1` (a perfect sensor, believed completely); and `Q = 0, a > 1`
/// gives `K = 1 − 1/a²`.
///
/// # What it is not
///
/// Not a robot's state estimator. One state, one measurement, constant `Q` and `R`, no control
/// input in the prediction, no Joseph form, no outlier handling. Extending it to a vector state
/// needs a matrix inverse and this crate has no linear algebra beyond
/// [`crate::reservoir::cholesky`]; the honest move is to say so rather than to ship a 2×2 special
/// case and call it general.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ScalarKalman {
    /// State transition coefficient, dimensionless. `1` is a random walk.
    pub a: f64,
    /// Process-noise variance per step, in squared state units. Non-negative.
    pub q: f64,
    /// Measurement-noise variance, in squared state units. Non-negative.
    pub r: f64,
    /// Current state estimate, state units.
    pub x: f64,
    /// Current posterior variance, squared state units.
    pub p: f64,
}

impl ScalarKalman {
    /// Build with a transition coefficient, process and measurement variances, and a prior.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for any non-finite argument; [`ControlError::NotPositive`] for
    /// a negative `q`, a negative `r` or a negative `p0`. Zero is accepted for all three — they
    /// are the exactly-solvable limits the doc names.
    pub fn new(a: f64, q: f64, r: f64, x0: f64, p0: f64) -> Result<Self, ControlError> {
        for (what, v) in [("a", a), ("q", q), ("r", r), ("x0", x0), ("p0", p0)] {
            need_finite(what, v)?;
        }
        for (what, v) in [("q (may be zero)", q), ("r (may be zero)", r), ("p0 (may be zero)", p0)] {
            if v < 0.0 {
                return Err(ControlError::NotPositive { what, value: v });
            }
        }
        Ok(Self { a, q, r, x: x0, p: p0 })
    }

    /// The steady-state **prior** variance, in closed form. See the type doc for the derivation.
    #[must_use]
    pub fn steady_state_prior_variance(&self) -> f64 {
        let (q, r, a2) = (self.q, self.r, self.a * self.a);
        let b = r - a2 * r - q;
        0.5 * (-b + (b * b + 4.0 * q * r).sqrt())
    }

    /// The steady-state Kalman gain, in closed form: `p/(p + R)`.
    ///
    /// `None` when `p + R` is zero — a noiseless constant observed by a noiseless sensor, where
    /// the first measurement is the answer and there is no recursion to converge to.
    #[must_use]
    pub fn steady_state_gain(&self) -> Option<f64> {
        let p = self.steady_state_prior_variance();
        let d = p + self.r;
        if d <= 0.0 { None } else { Some(p / d) }
    }

    /// Propagate the estimate and its variance one step forward, applying no measurement.
    pub fn predict(&mut self) {
        self.x *= self.a;
        self.p = self.a * self.a * self.p + self.q;
    }

    /// Fold in a measurement, returning the posterior estimate.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for a non-finite `z`; [`ControlError::NotPositive`] when the
    /// innovation variance `p + R` is zero, where the gain is undefined rather than one.
    pub fn update(&mut self, z: f64) -> Result<f64, ControlError> {
        need_finite("measurement", z)?;
        let s = self.p + self.r;
        if !(s > 0.0) {
            return Err(ControlError::NotPositive { what: "innovation variance p + r", value: s });
        }
        let k = self.p / s;
        self.x += k * (z - self.x);
        self.p *= 1.0 - k;
        Ok(self.x)
    }

    /// [`ScalarKalman::predict`] then [`ScalarKalman::update`].
    ///
    /// # Errors
    ///
    /// As [`ScalarKalman::update`].
    pub fn step(&mut self, z: f64) -> Result<f64, ControlError> {
        self.predict();
        self.update(z)
    }
}

/// A population-coded state estimator: decode spike counts, then filter.
///
/// The measurement comes from a [`crate::coding::GaussianPopulation`] observed for a fixed window;
/// its centre-of-mass decode feeds a [`ScalarKalman`] whose measurement variance is set from the
/// population's **Cramér-Rao bound**, `R = 1 / I(x)`, rather than from a number the caller made up.
///
/// # The three assumptions the population code violates, named
///
/// 1. **The decode is biased near the ends of the coded range.** Cells sit on `lo` and `hi`, so a
///    stimulus near either end has neighbours on one side only and the centre-of-mass estimate is
///    pulled inward. The filter's noise model has no bias term, so it treats that pull as a real
///    movement of the state. [`crate::coding::GaussianPopulation::interior`] computes the sub-range
///    where the bias is below a tolerance, and that is the range to use.
/// 2. **The Cramér-Rao bound is a bound, not the variance.** It is the smallest variance an
///    *unbiased* decoder could achieve. Centre-of-mass is not that decoder, so `R` here is
///    **optimistic** and the filter is correspondingly over-confident;
///    [`crate::coding::GaussianPopulation::decode_max_likelihood`] is the estimator that actually
///    attains the bound, and this crate measures the gap in `coding`'s own tests.
/// 3. **The measurement noise is Poisson, not Gaussian.** At the count levels a real window
///    produces the difference is small and the filter is still the minimum-variance *linear*
///    estimator, which is the honest claim; it is not the optimal estimator.
///
/// `R` is evaluated at a **fixed reference stimulus** supplied at construction, because Fisher
/// information depends on where in the range you are, and recomputing it at the current estimate
/// would let the filter tune its own noise model from its own output.
#[derive(Debug, Clone, PartialEq)]
pub struct PopulationEstimator {
    /// The tuning curves the measurement is decoded against.
    pub pop: GaussianPopulation,
    /// The scalar filter, with `r` already set from the Cramér-Rao bound.
    pub filter: ScalarKalman,
    /// Observation window, seconds — the same window the counts were collected over.
    pub window_s: f64,
    /// Total spikes folded in so far, across every cell and every observation.
    pub spikes: u64,
}

impl PopulationEstimator {
    /// Build, taking `R` from the population's Fisher information at `reference_x`.
    ///
    /// # Errors
    ///
    /// [`ControlError::Coding`] wrapping whatever
    /// [`crate::coding::GaussianPopulation::fisher_information`] refused with — a non-finite
    /// reference, a non-positive window, or a population carrying no information at that point.
    /// [`ControlError::NotFinite`] or [`ControlError::NotPositive`] from [`ScalarKalman::new`].
    pub fn new(
        pop: GaussianPopulation,
        a: f64,
        q: f64,
        window_s: f64,
        reference_x: f64,
        x0: f64,
    ) -> Result<Self, ControlError> {
        let info = pop.fisher_information(reference_x, window_s)?;
        let r = 1.0 / info;
        let filter = ScalarKalman::new(a, q, r, x0, r)?;
        Ok(Self { pop, filter, window_s, spikes: 0 })
    }

    /// The measurement variance the filter is using, squared stimulus units: `1 / I(reference_x)`.
    #[must_use]
    pub fn measurement_variance(&self) -> f64 {
        self.filter.r
    }

    /// Decode one window of spike counts and fold it in, returning the posterior estimate.
    ///
    /// # Errors
    ///
    /// [`ControlError::Coding`] if the counts do not match the population, or if no cell exceeded
    /// baseline — a silent population carries no measurement, and this refuses rather than
    /// folding in the midpoint of the range. [`ControlError::NotPositive`] from the filter.
    pub fn observe(&mut self, counts: &[u64]) -> Result<f64, ControlError> {
        let rates = rates_from_counts(counts, self.window_s)?;
        let z = self.pop.decode_center_of_mass(&rates)?;
        self.spikes += counts.iter().sum::<u64>();
        self.filter.step(z)
    }
}

