/// What a controller's run costs, in the counts [`crate::ledger::Ledger`] prices.
///
/// The headline number is [`ControlBudget::spikes_per_second`] — **spikes per second of control**,
/// which is the quantity a spiking controller is supposed to make small and which nothing else in
/// this crate measures, because nothing else in this crate acts.
///
/// The `mode` is load-bearing. A clocked implementation updates every cell on every tick whether
/// or not the error is non-zero, so a controller sitting at its setpoint still pays
/// `neurons · ticks` membrane updates; an event-driven one pays none. The difference shows up as
/// [`crate::ledger::Ledger::idle_fraction`], and for a held setpoint it is exactly `1.0` — every
/// update the clock paid for did nothing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ControlBudget {
    /// Spikes the controller's error encoder emitted.
    pub spikes: u64,
    /// Seconds of control, as an integer number of nanoseconds so the type stays `Eq`.
    pub duration_ns: u64,
    /// Clock ticks the run took.
    pub ticks: u64,
    /// Cells in the error population — two for a push-pull encoder.
    pub neurons: u64,
    /// Synapses each spike is delivered to. Three for a full PID controller, because the P, I and
    /// D terms are three synapses on **one** spike train rather than three computations.
    pub synapses_per_spike: u64,
    /// Whether the implementation being priced updates on a clock or on events.
    pub mode: Mode,
}

impl ControlBudget {
    /// Assemble from a run's counts. `duration_s` is rounded to the nearest nanosecond.
    #[must_use]
    pub fn new(
        spikes: u64,
        duration_s: f64,
        ticks: u64,
        neurons: u64,
        synapses_per_spike: u64,
        mode: Mode,
    ) -> Self {
        let ns = if duration_s.is_finite() && duration_s > 0.0 {
            (duration_s * 1e9).round().max(0.0) as u64
        } else {
            0
        };
        Self { spikes, duration_ns: ns, ticks, neurons, synapses_per_spike, mode }
    }

    /// Seconds of control.
    #[must_use]
    pub fn duration_s(&self) -> f64 {
        self.duration_ns as f64 * 1e-9
    }

    /// **Spikes per second of control.** `None` for a run of zero length, where the ratio is not a
    /// rate of anything.
    #[must_use]
    pub fn spikes_per_second(&self) -> Option<f64> {
        if self.duration_ns == 0 {
            return None;
        }
        Some(self.spikes as f64 / self.duration_s())
    }

    /// Translate into the crate's ledger so the same prices apply as to any other workload.
    ///
    /// Synaptic operations are `spikes · synapses_per_spike`, one weight fetch each. Membrane
    /// updates split by mode: **one driven update per spike**, capped at the total the clock could
    /// have performed, and then [`Mode::Clocked`] charges the remaining `neurons · ticks − driven`
    /// as idle while [`Mode::EventDriven`] charges none of them. A spike is counted as routed once.
    #[must_use]
    pub fn to_ledger(&self) -> Ledger {
        let syn = self.spikes.saturating_mul(self.synapses_per_spike);
        let driven = self.spikes.min(self.ticks.saturating_mul(self.neurons));
        let total = self.ticks.saturating_mul(self.neurons);
        let idle = match self.mode {
            Mode::Clocked => total.saturating_sub(driven),
            Mode::EventDriven => 0,
        };
        Ledger {
            syn_ops: syn,
            syn_fetches: syn,
            neuron_updates_idle: idle,
            neuron_updates_driven: driven,
            spikes_out: self.spikes,
            reads: 0,
        }
    }
}

impl fmt::Display for ControlBudget {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.spikes_per_second() {
            Some(r) => write!(f, "{:.1} spikes/s over {:.3} s", r, self.duration_s()),
            None => f.write_str("no control time elapsed; no rate"),
        }
    }
}

