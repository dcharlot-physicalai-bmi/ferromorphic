    /// A trace normalised to unit DC gain must average to the spike rate that drives it, exactly.
    /// Every gain in [`SpikingPid`] is stated on the assumption that it does.
    #[test]
    fn the_trace_averages_to_the_rate_that_drives_it() {
        for &tau in &[2e-3, 20e-3, 200e-3] {
            let mut tr = Trace::new(tau).unwrap();
            let mut enc = SigmaDeltaEncoder::new(300.0).unwrap();
            // The trace decays THEN deposits, and this samples right after the deposit, which
            // biases the mean high by exactly dt/(2·tau) of it. The step is tied to tau so that
            // residual is 5e-4 rather than something that grows as tau shrinks; the tolerance is
            // three times it, and a DC gain wrong by the usual mistakes — depositing 1 instead of
            // 1/tau, or omitting the decay — is wrong by a factor of tau, not by 0.1%.
            let dt = tau / 1_000.0;
            let steps = (4.0 / dt).round() as usize; // 4 s, many multiples of every tau above
            let mut sum = 0.0;
            for i in 0..steps {
                let n = enc.step(dt, 1.0).unwrap();
                let v = tr.step(dt, n).unwrap();
                if i >= steps / 2 {
                    sum += v;
                }
            }
            let mean = sum / (steps - steps / 2) as f64;
            assert!((mean / 300.0 - 1.0).abs() < 1.5e-3, "tau {tau}: mean trace {mean}, rate 300");
        }
    }

    /// The exact identity the D term is built on: a first-order low-pass fed a ramp lags it by
    /// exactly its own time constant, so a fast arm minus a slow arm gives the slope times the
    /// difference of the constants. Checked on the traces themselves, with no spikes in the way,
    /// because this is an analytic statement about the filters.
    #[test]
    fn the_trace_difference_is_a_derivative_with_gain_tau_slow_minus_tau_fast() {
        let (tau_f, tau_s, dt) = (20e-3, 200e-3, 1e-6);
        let slope = 700.0; // hertz per second
        // Drive both with a continuous rate rather than spikes: deposit `r·dt` spikes' worth each
        // step, which is the same filter without the quantiser. The deposit-after-decay
        // convention biases each arm high by r·dt/(2·tau), so the difference carries a residual
        // of r·(dt/2)·(1/tau_f − 1/tau_s) — 2.5e-4 of the answer at this step size, well inside
        // the tolerance and named rather than absorbed.
        let ramp = |steps: usize, constant: bool| {
            let mut fast = Trace::new(tau_f).unwrap();
            let mut slow = Trace::new(tau_s).unwrap();
            let mut t = 0.0;
            for _ in 0..steps {
                let r = if constant { slope } else { slope * t };
                fast.x *= (-dt / tau_f).exp();
                fast.x += r * dt / tau_f;
                slow.x *= (-dt / tau_s).exp();
                slow.x += r * dt / tau_s;
                t += dt;
            }
            fast.value() - slow.value()
        };
        let got = ramp(2_000_000, false); // 2 s = 10 tau_s, transient down to 4.5e-5
        let want = slope * (tau_s - tau_f);
        assert!((got / want - 1.0).abs() < 1e-3, "ramp lag gave {got}, closed form {want}");
        // ANTI-VACUITY: the same tolerance must reject the neighbouring wrong answers — the sum
        // of the constants, or either one alone.
        for wrong in [slope * (tau_s + tau_f), slope * tau_s, slope * tau_f] {
            assert!((got / wrong - 1.0).abs() > 0.05, "cannot distinguish {want} from {wrong}");
        }
        // And the DC gain of the difference is zero: a CONSTANT rate leaves nothing behind.
        let dc = ramp(4_000_000, true);
        assert!(dc.abs() < 1e-3 * slope, "the high-pass passed {dc} of a constant {slope}");
    }

    // -----------------------------------------------------------------------------------------
    // ⭐ (a) THE SPIKING PID DRIVES ITS PLANT, AND THE OFFSET MATCHES THE CLOSED FORM
    // -----------------------------------------------------------------------------------------

    fn run_loop(spec: SpikingPidSpec, k: f64, tau: f64, setpoint: f64, seconds: f64) -> (f64, u64) {
        let mut pid = SpikingPid::new(spec).unwrap();
        let mut plant = FirstOrder::new(tau, k).unwrap();
        let dt = 1e-5;
        let steps = (seconds / dt).round() as usize;
        let mut sum = 0.0;
        let mut counted = 0usize;
        for i in 0..steps {
            let e = setpoint - plant.y;
            let u = pid.step(dt, e).unwrap();
            plant.step(dt, u).unwrap();
            // Average over the last quarter of the run, which is many closed-loop time constants
            // after the step.
            if i >= steps - steps / 4 {
                sum += setpoint - plant.y;
                counted += 1;
            }
        }
        (sum / counted as f64, pid.spikes())
    }

    /// ⭐ THE HEADLINE. A spiking controller drives a first-order plant, and its standing error
    /// matches `setpoint/(1 + k·Kp)` across a sweep of gains.
    ///
    /// The sweep is what makes it a check rather than a demo: the tolerance is 1%, and the
    /// predictions for adjacent gains differ by 33% or more, so a controller whose effective gain
    /// were off by one step of the sweep would fail. That is asserted explicitly below.
    #[test]
    fn the_spiking_pid_matches_the_closed_form_steady_state_error() {
        let (k, tau, setpoint) = (1.3, 0.2, 1.0);
        let plant = FirstOrder::new(tau, k).unwrap();
        let gains = [1.0, 2.0, 4.0, 8.0];
        let mut measured = Vec::new();
        for &kp in &gains {
            let spec = SpikingPidSpec::proportional(20_000.0, kp, 5e-3);
            let (e, spikes) = run_loop(spec, k, tau, setpoint, 3.0);
            let want = plant.p_only_steady_state_error(setpoint, kp);
            assert!(
                (e / want - 1.0).abs() < 0.01,
                "Kp {kp}: measured {e}, closed form {want} ({spikes} spikes)"
            );
            measured.push(e);
        }
        // ⛔ THE NEGATIVE HALF. Every closed-form test in this module drove the controller with a
        // strictly positive error, so the `p_neg` and `d_*_neg` arms could be replaced with the
        // positive ones and 45 tests stayed green — while a controller asked to go DOWN burnt
        // 60,000 spikes and never moved the plant. The controller is exactly antisymmetric,
        // `u(-e) = -u(e)`, so the same sweep at setpoint -1 must land on the negated prediction.
        for &kp in &gains {
            let spec = SpikingPidSpec::proportional(20_000.0, kp, 5e-3);
            let (e, spikes) = run_loop(spec, k, tau, -setpoint, 3.0);
            let want = plant.p_only_steady_state_error(-setpoint, kp);
            assert!(want < 0.0, "the closed form must be negative for a negative setpoint");
            assert!(
                (e / want - 1.0).abs() < 0.01,
                "Kp {kp}, setpoint -1: measured {e}, closed form {want} ({spikes} spikes)"
            );
        }

        // ANTI-VACUITY: the tolerance must be tighter than the sweep's own spacing, or a
        // controller with the wrong gain would pass. Every measured error is checked to be far
        // from every OTHER gain's prediction.
        for (i, &e) in measured.iter().enumerate() {
            for (j, &kp) in gains.iter().enumerate() {
                if i == j {
                    continue;
                }
                let other = plant.p_only_steady_state_error(setpoint, kp);
                assert!(
                    (e / other - 1.0).abs() > 0.1,
                    "the measurement for gain {} is within 10% of gain {kp}'s prediction; the \
                     sweep does not discriminate",
                    gains[i]
                );
            }
        }
    }

