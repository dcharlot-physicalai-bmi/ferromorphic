/// What [`measure_period`] found.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PeriodEstimate {
    /// Mean interval between consecutive upward crossings of the mid-level, seconds.
    pub period_s: f64,
    /// Complete cycles the estimate averages over. At least two.
    pub cycles: usize,
    /// Largest deviation of any single cycle from the mean, seconds. A limit cycle has a jitter
    /// far below its period; a transient or a quasi-periodic signal does not, and this is how a
    /// caller tells the difference without plotting anything.
    pub jitter_s: f64,
}

impl PeriodEstimate {
    /// Cycles per second.
    #[must_use]
    pub fn frequency_hz(&self) -> f64 {
        1.0 / self.period_s
    }

    /// Jitter as a fraction of the period — the number to threshold on.
    #[must_use]
    pub fn relative_jitter(&self) -> f64 {
        self.jitter_s / self.period_s
    }
}

/// Upward crossings of the mid-level, in seconds, with sub-sample linear interpolation.
///
/// The mid-level is `(min + max)/2` of the samples supplied, which is what makes the measurement
/// work on a rectified oscillator output (floor at zero), on a burst envelope (floor at zero) and
/// on a pendulum angle (symmetric about zero) without a threshold argument to get wrong.
fn up_crossings(samples: &[f64], dt: f64) -> Vec<f64> {
    let mut lo = f64::INFINITY;
    let mut hi = f64::NEG_INFINITY;
    for &s in samples {
        if s < lo {
            lo = s;
        }
        if s > hi {
            hi = s;
        }
    }
    if !(hi > lo) {
        return Vec::new();
    }
    let mid = 0.5 * (lo + hi);
    let mut out = Vec::new();
    for i in 1..samples.len() {
        let (a, b) = (samples[i - 1], samples[i]);
        if a < mid && b >= mid {
            // Linear interpolation of the crossing instant. Without it the measured period is
            // quantised to dt, which for a 0.1% tolerance at dt = 1e-4 s would need a period above
            // 0.1 s to pass for the wrong reason.
            let frac = (mid - a) / (b - a);
            out.push((i - 1) as f64 * dt + frac * dt);
        }
    }
    out
}

/// Measure the period of a sampled oscillation.
///
/// Pass the **settled** portion of a run: this function does not discard a transient, and
/// [`PeriodEstimate::jitter_s`] is how it tells you that you should have.
///
/// # Errors
///
/// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::TooFewCycles`] when
/// fewer than three upward mid-level crossings were found, which includes every non-oscillating
/// signal — a constant, a monotone ramp, and a decaying transient all return the refusal rather
/// than a number.
pub fn measure_period(samples: &[f64], dt: f64) -> Result<PeriodEstimate, ControlError> {
    need_positive("dt", dt)?;
    let xs = up_crossings(samples, dt);
    if xs.len() < 3 {
        return Err(ControlError::TooFewCycles { found: xs.len(), needed: 3 });
    }
    let intervals: Vec<f64> = xs.windows(2).map(|w| w[1] - w[0]).collect();
    let mean = intervals.iter().sum::<f64>() / intervals.len() as f64;
    let jitter = intervals.iter().map(|&i| (i - mean).abs()).fold(0.0, f64::max);
    Ok(PeriodEstimate { period_s: mean, cycles: intervals.len(), jitter_s: jitter })
}

/// Phase of `b` relative to `a`, radians in `[0, 2π)`.
///
/// Measured as the lag between the first settled upward crossing of `a` and the next upward
/// crossing of `b`, divided by `a`'s period. **π is strict anti-phase**, which is the property
/// that makes a pair of half-centres a gait generator rather than a single oversized oscillator.
///
/// # Errors
///
/// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::TooFewCycles`] if either
/// signal has fewer than three crossings; [`ControlError::PeriodMismatch`] when the two measured
/// periods differ by more than 5%, because two signals at different frequencies have a phase that
/// drifts and reporting one instant of it would be a number that plots.
pub fn phase_difference(a: &[f64], b: &[f64], dt: f64) -> Result<f64, ControlError> {
    let pa = measure_period(a, dt)?;
    let pb = measure_period(b, dt)?;
    if (pa.period_s - pb.period_s).abs() > 0.05 * pa.period_s {
        return Err(ControlError::PeriodMismatch { a_s: pa.period_s, b_s: pb.period_s });
    }
    let xa = up_crossings(a, dt);
    let xb = up_crossings(b, dt);
    let t0 = xa[0];
    // The first b-crossing at or after a's reference crossing; if b crossed only before it, wrap
    // forward by one of b's periods so the lag is still in [0, T).
    let lag = match xb.iter().find(|&&t| t >= t0) {
        Some(&t) => t - t0,
        None => xb[xb.len() - 1] + pb.period_s - t0,
    };
    let frac = (lag / pa.period_s).rem_euclid(1.0);
    Ok(frac * TAU)
}

