/// A first-order plant: `tau · dy/dt = −y + k · u`.
///
/// The simplest thing a controller can be wrong about, and the reason it is here is that
/// everything about it is closed form — the step response, the settling time, and the standing
/// offset a proportional controller leaves.
///
/// Integrated by **exponential Euler**, which for piecewise-constant `u` is the exact solution
/// over the step rather than an approximation to it, so a comparison against the closed form
/// measures the controller and not the integrator.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FirstOrder {
    /// Time constant, seconds. Strictly positive.
    pub tau: f64,
    /// DC gain, output units per input unit. May be negative; may not be zero, since a plant the
    /// input cannot move has no control problem.
    pub k: f64,
    /// Current output, in the plant's own units.
    pub y: f64,
}

impl FirstOrder {
    /// Build at rest, `y = 0`.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `tau` or a `k` of zero;
    /// [`ControlError::NotFinite`] for a non-finite `k`.
    pub fn new(tau: f64, k: f64) -> Result<Self, ControlError> {
        need_positive("tau", tau)?;
        need_finite("k", k)?;
        if k == 0.0 {
            return Err(ControlError::NotPositive { what: "|k| (a plant u cannot move)", value: k });
        }
        Ok(Self { tau, k, y: 0.0 })
    }

    /// Advance by `dt` under constant input `u`, returning the new output.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::NotFinite`] for a
    /// non-finite `u`.
    pub fn step(&mut self, dt: f64, u: f64) -> Result<f64, ControlError> {
        need_positive("dt", dt)?;
        need_finite("plant input", u)?;
        let y_inf = self.k * u;
        self.y = y_inf + (self.y - y_inf) * (-dt / self.tau).exp();
        Ok(self.y)
    }

    /// The closed-form output at time `t` after starting from `y0` under constant `u`.
    ///
    /// `y(t) = k·u + (y0 − k·u)·exp(−t/tau)`.
    #[must_use]
    pub fn response(&self, y0: f64, u: f64, t: f64) -> f64 {
        let y_inf = self.k * u;
        y_inf + (y0 - y_inf) * (-t / self.tau).exp()
    }

    /// **The closed form this module's headline test checks.**
    ///
    /// Under a proportional controller `u = Kp · (setpoint − y)` the loop settles where
    /// `0 = −y + k·Kp·(setpoint − y)`, so the standing error is
    ///
    /// ```text
    /// e_ss = setpoint / (1 + k · Kp)
    /// ```
    ///
    /// It is never zero for finite gain, which is the textbook reason integral action exists, and
    /// it is the number [`SpikingPid`] is graded against across a sweep of `Kp`. Returns `None`
    /// when `1 + k·Kp` is zero — positive feedback exactly cancelling the plant, where the loop
    /// has no equilibrium at all rather than a large one.
    #[must_use]
    pub fn p_only_steady_state_error_checked(&self, setpoint: f64, kp: f64) -> Option<f64> {
        let denom = 1.0 + self.k * kp;
        if denom == 0.0 || !denom.is_finite() {
            return None;
        }
        Some(setpoint / denom)
    }

    /// [`FirstOrder::p_only_steady_state_error_checked`] with the degenerate case mapped to `NaN`.
    ///
    /// For the common case where the caller has already chosen a stabilising gain and wants the
    /// number without unwrapping. A `NaN` here means the loop has no equilibrium, and it will
    /// propagate into any comparison rather than read as a small error.
    #[must_use]
    pub fn p_only_steady_state_error(&self, setpoint: f64, kp: f64) -> f64 {
        self.p_only_steady_state_error_checked(setpoint, kp).unwrap_or(f64::NAN)
    }

    /// Seconds for the plant's **open-loop** step response to fall within `frac` of its final
    /// value: `tau · ln(1/frac)`. (This line used to say "closed-loop ... for the open-loop plant",
    /// which contradicts itself; the formula is the open-loop plant's.)
    ///
    /// `None` unless `0 < frac < 1`.
    #[must_use]
    pub fn settling_time(&self, frac: f64) -> Option<f64> {
        if !(frac > 0.0 && frac < 1.0) {
            return None;
        }
        Some(self.tau * (1.0 / frac).ln())
    }
}

/// A rigid pendulum with viscous damping and a torque input.
///
/// ```text
/// theta'' = −(g/L)·sin(theta) − (b/(m·L²))·theta' + tau_in/(m·L²)
/// ```
///
/// `theta` is measured from **hanging down**, so `theta = 0, omega = 0, tau_in = 0` is an exact
/// fixed point — which is what makes it the plant for the "already at setpoint" test: a controller
/// holding this pendulum where it already is has to emit nothing, and the state must not move at
/// all rather than move a little.
///
/// Integrated by classical fourth-order Runge-Kutta. The closed forms it is checked against are
/// the **exact** nonlinear period through [`complete_elliptic_k`] and the conservation of
/// [`Pendulum::energy`] when undamped and unforced — the second of which is a genuine constraint on
/// the integrator, since RK4 is not symplectic and its energy drift is what the test bounds.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Pendulum {
    /// Rod length, metres. Strictly positive.
    pub length_m: f64,
    /// Bob mass, kilograms. Strictly positive.
    pub mass_kg: f64,
    /// Gravitational acceleration, metres per second squared. Strictly positive.
    pub gravity: f64,
    /// Viscous damping coefficient, newton-metre-seconds per radian. Non-negative; zero is the
    /// conservative case the period formula is exact for.
    pub damping: f64,
    /// Angle from hanging down, radians.
    pub theta: f64,
    /// Angular velocity, radians per second.
    pub omega: f64,
}

impl Pendulum {
    /// Build at rest hanging down, with standard gravity and no damping.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive length, mass or gravity, or a negative
    /// damping.
    pub fn new(length_m: f64, mass_kg: f64) -> Result<Self, ControlError> {
        need_positive("length_m", length_m)?;
        need_positive("mass_kg", mass_kg)?;
        Ok(Self {
            length_m,
            mass_kg,
            gravity: 9.80665,
            damping: 0.0,
            theta: 0.0,
            omega: 0.0,
        })
    }

    /// Set the viscous damping coefficient, newton-metre-seconds per radian.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotFinite`] for a non-finite value, [`ControlError::NotPositive`] for a
    /// negative one. Zero is accepted.
    pub fn with_damping(mut self, b: f64) -> Result<Self, ControlError> {
        need_finite("damping", b)?;
        if b < 0.0 {
            return Err(ControlError::NotPositive { what: "damping (may be zero)", value: b });
        }
        self.damping = b;
        Ok(self)
    }

    /// Moment of inertia about the pivot, kilogram metres squared: `m·L²`.
    #[must_use]
    pub fn inertia(&self) -> f64 {
        self.mass_kg * self.length_m * self.length_m
    }

    /// Total mechanical energy, joules: `½·m·L²·omega² + m·g·L·(1 − cos theta)`, zero at rest
    /// hanging down.
    #[must_use]
    pub fn energy(&self) -> f64 {
        0.5 * self.inertia() * self.omega * self.omega
            + self.mass_kg * self.gravity * self.length_m * (1.0 - self.theta.cos())
    }

    fn accel(&self, theta: f64, omega: f64, torque_nm: f64) -> f64 {
        -(self.gravity / self.length_m) * theta.sin() - (self.damping / self.inertia()) * omega
            + torque_nm / self.inertia()
    }

    /// Advance by `dt` seconds under a constant applied torque, newton-metres.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] for a non-positive `dt`; [`ControlError::NotFinite`] for a
    /// non-finite torque.
    pub fn step(&mut self, dt: f64, torque_nm: f64) -> Result<(), ControlError> {
        need_positive("dt", dt)?;
        need_finite("torque", torque_nm)?;
        let (t0, w0) = (self.theta, self.omega);
        let k1t = w0;
        let k1w = self.accel(t0, w0, torque_nm);
        let k2t = w0 + 0.5 * dt * k1w;
        let k2w = self.accel(t0 + 0.5 * dt * k1t, w0 + 0.5 * dt * k1w, torque_nm);
        let k3t = w0 + 0.5 * dt * k2w;
        let k3w = self.accel(t0 + 0.5 * dt * k2t, w0 + 0.5 * dt * k2w, torque_nm);
        let k4t = w0 + dt * k3w;
        let k4w = self.accel(t0 + dt * k3t, w0 + dt * k3w, torque_nm);
        self.theta += dt / 6.0 * (k1t + 2.0 * k2t + 2.0 * k3t + k4t);
        self.omega += dt / 6.0 * (k1w + 2.0 * k2w + 2.0 * k3w + k4w);
        Ok(())
    }

    /// The small-angle period, seconds: `2π·sqrt(L/g)`.
    ///
    /// The number everyone remembers, and an **underestimate** at every finite amplitude — by 1.7%
    /// at 30°, by 18% at 90° and by 37% at 120° (`K(sin 60°)/(π/2) = 1.3729`; the first version
    /// of this line printed the 90° figure against the 120° label). [`Pendulum::exact_period`] is
    /// the one to compare a simulation against, and the gap between the two is what makes that
    /// comparison worth making.
    #[must_use]
    pub fn small_angle_period(&self) -> f64 {
        TAU * (self.length_m / self.gravity).sqrt()
    }

    /// The **exact** period of an undamped pendulum released from rest at `theta0`, seconds:
    ///
    /// ```text
    /// T = 4·sqrt(L/g)·K( sin(theta0/2) )
    /// ```
    ///
    /// with `K` the complete elliptic integral of the first kind in the **modulus** convention
    /// (see [`complete_elliptic_k`]). Standard; derived in any mechanics text from energy
    /// conservation, e.g. Landau and Lifshitz, *Mechanics*, §11 problem 1.
    ///
    /// # Errors
    ///
    /// [`ControlError::NotPositive`] if `damping` is non-zero — a damped pendulum's successive
    /// swings have different durations and there is no period to report.
    /// [`ControlError::AngleOutOfRange`] for `|theta0| ≥ π`, where the motion is no longer a
    /// libration: at exactly π the pendulum takes infinite time to leave the top, and beyond it,
    /// released from rest, it does not reach the top at all in the same sense.
    /// [`ControlError::NotFinite`] for a non-finite `theta0`.
    pub fn exact_period(&self, theta0: f64) -> Result<f64, ControlError> {
        need_finite("theta0", theta0)?;
        if self.damping != 0.0 {
            return Err(ControlError::NotPositive {
                what: "1/damping (a damped pendulum has no period)",
                value: self.damping,
            });
        }
        if theta0.abs() >= PI {
            return Err(ControlError::AngleOutOfRange { theta: theta0, limit: PI });
        }
        if theta0 == 0.0 {
            // The limit, and the only amplitude where the exact period equals the small-angle one.
            return Ok(self.small_angle_period());
        }
        let k = (0.5 * theta0.abs()).sin();
        let big_k = complete_elliptic_k(k)
            .ok_or(ControlError::AngleOutOfRange { theta: theta0, limit: PI })?;
        Ok(4.0 * (self.length_m / self.gravity).sqrt() * big_k)
    }
}

/// Complete elliptic integral of the first kind, **modulus** convention.
///
/// ```text
/// K(k) = ∫₀^{π/2} dθ / sqrt(1 − k²·sin²θ)  =  π / (2·AGM(1, sqrt(1 − k²)))
/// ```
///
/// Computed by Gauss's arithmetic-geometric mean, which converges quadratically — about five
/// iterations to full double precision — and is the method Abramowitz and Stegun give as 17.6.
///
/// **Which convention**: this takes the modulus `k`, not the parameter `m = k²`. Numerical
/// libraries disagree about this and it is the single most common way an elliptic-integral result
/// comes out wrong while looking plausible: `SciPy`'s `ellipk` takes `m`, `Mathematica`'s
/// `EllipticK` takes `m`, Abramowitz and Stegun tabulate against the modular angle. Check against
/// `K(0) = π/2` and `K(1/√2) = 1.854074677301372` before trusting any of them, this one included.
///
/// `None` for `|k| ≥ 1`, where the integral diverges, and for a non-finite `k`.
#[must_use]
pub fn complete_elliptic_k(k: f64) -> Option<f64> {
    if !k.is_finite() || k.abs() >= 1.0 {
        return None;
    }
    let mut a = 1.0;
    let mut b = (1.0 - k * k).sqrt();
    // Quadratic convergence: |a − b| squares each round. 40 is a bound nothing reaches, not a
    // tuned iteration count — the loop exits on the tolerance, and the cap only stops a
    // pathological input from spinning.
    for _ in 0..40 {
        if (a - b).abs() <= 1e-17 * a {
            break;
        }
        let a_next = 0.5 * (a + b);
        b = (a * b).sqrt();
        a = a_next;
    }
    Some(PI / (2.0 * a))
}

